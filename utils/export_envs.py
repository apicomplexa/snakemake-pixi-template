#!/usr/bin/env python
"""Export pixi environments to workflow/envs/ for Snakemake's `conda:` directive.

For every environment in pixi.toml except the interactive ones in SKIP it writes

    workflow/envs/<env>.yaml                  human-readable spec (version ranges)
    workflow/envs/<env>.<platform>.pin.txt    conda explicit spec (exact URLs + md5)

Snakemake installs from the `.pin.txt` matching the current platform when it
exists and falls back to the `.yaml` otherwise, so rule envs are bit-for-bit
the ones recorded in pixi.lock. Files generated by an earlier run for an env
that no longer exists are removed.

Usage: pixi run export-envs
"""

import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENVS_DIR = ROOT / "workflow" / "envs"
SKIP = {"default"}  # interactive-only environments, never used by rules
MARKER = "# Generated by utils/export_envs.py from pixi.lock - do not edit, run `pixi run export-envs`."


def pixi_export(*args: str) -> None:
    subprocess.run(["pixi", "workspace", "export", *args], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)


def export_yaml(env: str) -> Path:
    path = ENVS_DIR / f"{env}.yaml"
    pixi_export("conda-environment", "--environment", env, str(path))
    lines, seen_channels, in_channels = [], set(), False
    for line in path.read_text().splitlines():
        # pixi repeats `nodefaults` when it is listed in the workspace channels
        if line.startswith("channels:"):
            in_channels = True
        elif not line.startswith("- "):
            in_channels = False
        elif in_channels:
            if line in seen_channels:
                continue
            seen_channels.add(line)
        lines.append(line)
    path.write_text("\n".join([MARKER, *lines]) + "\n")
    return path


def export_pins(env: str) -> list[Path]:
    written = []
    with tempfile.TemporaryDirectory() as tmp:
        pixi_export("conda-explicit-spec", "--environment", env, tmp)
        for spec in Path(tmp).glob(f"{env}_*_conda_spec.txt"):
            platform = spec.name.removeprefix(f"{env}_").removesuffix("_conda_spec.txt")
            path = ENVS_DIR / f"{env}.{platform}.pin.txt"
            path.write_text(MARKER + "\n" + spec.read_text())
            written.append(path)
    return written


def main() -> int:
    manifest = tomllib.loads((ROOT / "pixi.toml").read_text())
    envs = [env for env in manifest.get("environments", {}) if env not in SKIP]
    ENVS_DIR.mkdir(parents=True, exist_ok=True)

    written = set()
    for env in envs:
        written.add(export_yaml(env))
        written.update(export_pins(env))

    for path in ENVS_DIR.iterdir():
        if path not in written and path.is_file() and path.read_text().startswith(MARKER):
            path.unlink()
            print(f"removed stale {path.relative_to(ROOT)}")

    for path in sorted(written):
        print(f"exported {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
